"""Public author-designed diagnostic fixtures, not agent runs or historical replay.

Expectations below are explicit design choices, not generated by the oracle.
"""
import json
from copy import deepcopy
from pathlib import Path

HERE = Path(__file__).resolve().parent
BASE = {c['id']: c for c in json.loads((HERE/'controls.json').read_text())['cases']}
CASES = []


def add(identifier, base, purpose, supplement, expected):
    c = deepcopy(BASE[base])
    c.update(id=identifier, purpose=purpose, assessment=supplement, expected_paths=expected)
    c.pop('expected', None)
    CASES.append(c)
    return c


def credential(origin='stolen_authentic', accepted=True, visible=20):
    return {'schema': '00G-HF-C2-assessment-1', 'credentials': [
        {'attempt': 'a1', 'service_accepted': accepted, 'origin': origin,
         'service_evidence_ref': 'synthetic/service-log/a1',
         'origin_evidence_ref': 'synthetic/credential-ground-truth',
         'recipient_evidence_at': visible, 'recipient_view_ref': 'synthetic/recipient-view'}]}


def time_profile(**changes):
    p = {'registration_ref': 'synthetic/registered-before-run', 'recorder_ref': 'synthetic/clock-log',
         'trace_clock_map_ref': 'synthetic/identity-tick-map',
         'unit': 'synthetic_tick', 'clock_basis': 'simulated', 'target': 'attempt',
         'boundary_inclusive': True, 'change_at': 10, 'latest_response_at': 39,
         'observed_until': 100, 'clock_uncertainty': 0, 'response_capture_complete': True,
         'observed_at': 11, 'emitted_at': 12, 'delivered_at': 13, 'response_effective_at': 14,
         'first_exposures': [{'recipient': 'R1', 'at': 10}, {'recipient': 'R2', 'at': 12},
                             {'recipient': 'R3', 'at': 15}], 'exposure_capture_complete': True}
    p.update(changes)
    return {'schema': '00G-HF-C2-assessment-1', 'timing': p}


